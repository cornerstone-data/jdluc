def iter_tile_cluster_to_iso_3166s(
    iso_3166s: collections.abc.Sequence[str],
) -> collections.abc.Iterator[tuple[set[str], set[str]]]:
    continent_to_iso_3166s: dict[Continent, set[str]] = collections.defaultdict(
        set[str]
    )
    for iso_3166 in iso_3166s:
        continent_to_iso_3166s[ISO_3166_TO_CONTINENT[iso_3166]].add(iso_3166)
    for continent, iso_3166_cluster in continent_to_iso_3166s.items():
        yield set(continent.value), iso_3166_cluster
